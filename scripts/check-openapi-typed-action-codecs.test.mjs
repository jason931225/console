import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { after, describe, it } from "node:test";
import { fileURLToPath } from "node:url";

import { ACTION_FLOOR, CANONICAL_ACTIONS } from "./check-openapi-semantic-contract.mjs";
import {
  INPUT_SCHEMA_NAMES,
  MANIFEST_REL,
  NESTED_INPUT_SCHEMAS,
} from "./check-openapi-semantic-generate.mjs";
import {
  CODEC_FLOOR,
  CODEC_SCHEMA_NAMES,
  TYPED_ACTION_GENERATED_REL,
  TYPED_ACTION_RS_REL,
  evaluateTypedActionCodecs,
} from "./check-openapi-typed-action-codecs.mjs";

const repoRoot = fileURLToPath(new URL("..", import.meta.url));
const cli = fileURLToPath(new URL("./check-openapi-typed-action-codecs.mjs", import.meta.url));
const fixtureRoots = [];

after(() => {
  for (const root of fixtureRoots) rmSync(root, { recursive: true, force: true });
});

function fixture(files) {
  const root = mkdtempSync(join(tmpdir(), "openapi-typed-action-codecs-"));
  fixtureRoots.push(root);
  for (const [rel, body] of Object.entries(files)) {
    const absolute = join(root, rel);
    mkdirSync(dirname(absolute), { recursive: true });
    writeFileSync(absolute, body);
  }
  return root;
}

function inputSchema(name, fields) {
  return {
    type: "object",
    additionalProperties: false,
    required: Object.keys(fields),
    properties: Object.fromEntries(
      Object.entries(fields).map(([field, type]) => [field, { type }]),
    ),
    description: name,
  };
}

function completeManifest() {
  const schemas = {};
  for (const name of INPUT_SCHEMA_NAMES) {
    schemas[name] = inputSchema(name, { marker: "string" });
  }
  schemas.EmploymentAttributesInput = inputSchema("EmploymentAttributesInput", {
    company: "string",
    employment_status: "string",
  });
  schemas.OrgUnitSourceBinding = inputSchema("OrgUnitSourceBinding", {
    kind: "string",
    id: "string",
  });
  return {
    version: 1,
    objects: [],
    links: [],
    actions: CANONICAL_ACTIONS.map((action) => ({
      action_key: action.action_key,
      object: action.object,
      object_key: action.object_key,
      input: action.input,
      four_eyes: action.four_eyes,
      edits: [...action.edits],
      permissions: ["role_manage"],
      concurrency: {
        command_id: "tenant_global_idempotency",
        expected_revision: "optional_cas",
      },
    })),
    schemas,
  };
}

function generatedRust(manifest) {
  const schemas = manifest.schemas;
  const structs = CODEC_SCHEMA_NAMES.map((name) => {
    const properties = schemas[name].properties;
    const fields = Object.keys(properties)
      .map((field) => `    ${field}: String,`)
      .join("\n");
    return `#[allow(dead_code)]
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct ${name} {
${fields}
}`;
  }).join("\n\n");
  const arms = CANONICAL_ACTIONS.map((action) => {
    const variant = action.action_key
      .split(/[._]/)
      .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
      .join("");
    return `        DispatchTarget::${variant} => decode::<${action.input}>(target, params),`;
  }).join("\n");
  return `// @generated by console-openapi-gen from semantic_manifest.json. Do not edit.

fn decode_dispatch_target(target: DispatchTarget, params: &Value) -> Result<(), ActionError> {
    match target {
${arms}
    }
}

${structs}
`;
}

const GREEN_EMITTER = `pub fn generated_typed_action_rs() -> Result<String, String> {
    let _ = include_str!("semantic_manifest.json");
    Ok(String::new())
}
`;

const GREEN_GEN = `fn main() {
    let _ = console_contracts::generated_typed_action_rs();
    let _ = "typed_action_generated.rs";
}
`;

const GREEN_BINDER = `pub(crate) fn bind_canonical_action_params() {}
include!("typed_action_generated.rs");
`;

function greenFiles(manifest, extra = {}) {
  return {
    [MANIFEST_REL]: JSON.stringify(manifest, null, 2),
    "backend/crates/contracts/src/semantic.rs": GREEN_EMITTER,
    "backend/crates/contracts/src/bin/console_openapi_gen.rs": GREEN_GEN,
    [TYPED_ACTION_RS_REL]: GREEN_BINDER,
    [TYPED_ACTION_GENERATED_REL]: generatedRust(manifest),
    ...extra,
  };
}

describe("typed-action-codecs floors", () => {
  it("locks examined-zero to 13 inputs + 2 nested write bags", () => {
    assert.equal(INPUT_SCHEMA_NAMES.length, ACTION_FLOOR);
    assert.equal(NESTED_INPUT_SCHEMAS.length, 2);
    assert.equal(CODEC_FLOOR, 15);
    assert.equal(new Set(CODEC_SCHEMA_NAMES).size, CODEC_FLOOR);
  });
});

describe("evaluateTypedActionCodecs", () => {
  it("fails when the manifest is absent", () => {
    const root = fixture({
      [TYPED_ACTION_RS_REL]: "pub(crate) fn bind_canonical_action_params() {}\n",
    });
    const result = evaluateTypedActionCodecs({ repoRoot: root });
    assert.equal(result.codecs, 0);
    assert.ok(
      result.findings.some((finding) => /semantic manifest is absent/.test(finding.message)),
    );
  });

  it("fails while typed_action.rs hand-defines CompanyReviseInput", () => {
    const manifest = completeManifest();
    const root = fixture(
      greenFiles(manifest, {
        [TYPED_ACTION_RS_REL]: `pub(crate) fn bind_canonical_action_params() {}
include!("typed_action_generated.rs");
#[derive(Deserialize)]
struct CompanyReviseInput {
    attributes: serde_json::Map<String, Value>,
}
`,
      }),
    );
    const result = evaluateTypedActionCodecs({ repoRoot: root });
    assert.ok(
      result.findings.some((finding) =>
        /hand-defines CompanyReviseInput/.test(finding.message),
      ),
      JSON.stringify(result.findings),
    );
  });

  it("fails when generated Rust is absent", () => {
    const manifest = completeManifest();
    const files = greenFiles(manifest);
    delete files[TYPED_ACTION_GENERATED_REL];
    const root = fixture(files);
    const result = evaluateTypedActionCodecs({ repoRoot: root });
    assert.ok(
      result.findings.some((finding) => /generated typed-action codecs are absent/.test(finding.message)),
      JSON.stringify(result.findings),
    );
  });

  it("fails when generated Rust drifts from a manifest field", () => {
    const manifest = completeManifest();
    const files = greenFiles(manifest);
    files[TYPED_ACTION_GENERATED_REL] = files[TYPED_ACTION_GENERATED_REL].replace(
      "    company: String,",
      "    renamed_company: String,",
    );
    const root = fixture(files);
    const result = evaluateTypedActionCodecs({ repoRoot: root });
    assert.ok(
      result.findings.some(
        (finding) =>
          finding.location.includes("EmploymentAttributesInput")
          && /drifted from the manifest/.test(finding.message),
      ),
      JSON.stringify(result.findings),
    );
  });

  it("passes a fixture whose codecs are generated from the manifest", () => {
    const manifest = completeManifest();
    const root = fixture(greenFiles(manifest));
    const result = evaluateTypedActionCodecs({ repoRoot: root });
    assert.deepEqual(result.findings, []);
    assert.equal(result.codecs, CODEC_FLOOR);
    assert.equal(result.actions, ACTION_FLOOR);
  });
});

describe("cli", () => {
  it("accepts the live binder only when codecs are generated from the semantic manifest", () => {
    const run = spawnSync(process.execPath, [cli, repoRoot], { encoding: "utf8" });
    assert.equal(run.status, 0, run.stderr);
    assert.match(run.stdout, /typed-action-codecs gate passed/);
  });
});
