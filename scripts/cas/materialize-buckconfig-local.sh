#!/usr/bin/env bash
# Materialize mode-0600 .buckconfig.local with NativeLink client mTLS paths.
# Never commits. Default lab root: ~/oyatie-cas/tls.
#
# Usage:
#   scripts/cas/materialize-buckconfig-local.sh              # writer (default)
#   scripts/cas/materialize-buckconfig-local.sh --role reader
#   scripts/cas/materialize-buckconfig-local.sh --role writer --tls-dir ~/oyatie-cas/tls
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
ROLE="writer"
TLS_DIR="${OYA_CAS_TLS_DIR:-$HOME/oyatie-cas/tls}"
OUT="${ROOT}/.buckconfig.local"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --role) ROLE="$2"; shift 2 ;;
    --tls-dir) TLS_DIR="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    -h|--help)
      sed -n '2,12p' "$0"
      exit 0
      ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

case "$ROLE" in
  writer) CERT="$TLS_DIR/client-writer.crt"; KEY="$TLS_DIR/client-writer.key" ;;
  reader) CERT="$TLS_DIR/client-reader.crt"; KEY="$TLS_DIR/client-reader.key" ;;
  *) echo "role must be writer|reader" >&2; exit 2 ;;
esac
CA="$TLS_DIR/ca.crt"

for f in "$CA" "$CERT" "$KEY"; do
  [[ -f "$f" ]] || { echo "missing TLS material: $f" >&2; exit 1; }
done

umask 077
cat >"$OUT" <<EOF
# GENERATED by scripts/cas/materialize-buckconfig-local.sh — do not commit.
# role=${ROLE}

[buck2_re_client]
  tls_ca_certs = ${CA}
  tls_client_cert = ${CERT}
  tls_client_key = ${KEY}
EOF
chmod 600 "$OUT"
echo "wrote ${OUT} (role=${ROLE}; mode $(stat -f '%Lp' "$OUT" 2>/dev/null || stat -c '%a' "$OUT"))"
