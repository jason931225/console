#!/usr/bin/env bash
# Materialize mode-0600 .buckconfig.local for NativeLink CAS warm builds.
#
# Buck2 OSS (2026-07-15) facts (proven locally):
# 1) REClientBuilder reads daemon root config (.buckconfig + .buckconfig.local).
#    `--config-file` alone does NOT supply engine_address ("No engine address").
# 2) Addresses are host:port (no grpcs://); tls=true selects TLS.
# 3) Client identity is a single PEM at tls_client_cert (cert + key concatenated).
#    There is no working tls_client_key knob in this Buck2 build's RE metadata.
#
# Usage:
#   scripts/cas/materialize-buckconfig-local.sh --profile lab-rw
#   scripts/cas/materialize-buckconfig-local.sh --profile gha-ro --tls-dir /tmp/cas-tls
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
ROLE=""
PROFILE=""
TLS_DIR="${CAS_TLS_DIR:-${OYA_CAS_TLS_DIR:-$HOME/oyatie-cas/tls}}"
OUT="${ROOT}/.buckconfig.local"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --role) ROLE="$2"; shift 2 ;;
    --profile) PROFILE="$2"; shift 2 ;;
    --tls-dir) TLS_DIR="$2"; shift 2 ;;
    --out) OUT="$2"; shift 2 ;;
    -h|--help)
      sed -n '2,18p' "$0"
      exit 0
      ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

if [[ -z "$PROFILE" ]]; then
  PROFILE=lab-rw
fi

case "$PROFILE" in
  lab-rw) ROLE=writer; ENDPOINT="127.0.0.1:50051"; UPLOAD=true ;;
  lab-ro) ROLE=reader; ENDPOINT="127.0.0.1:50052"; UPLOAD=false ;;
  gha-rw) ROLE=writer; ENDPOINT="127.0.0.1:55051"; UPLOAD=true ;;
  gha-ro) ROLE=reader; ENDPOINT="127.0.0.1:55052"; UPLOAD=false ;;
  *) echo "profile must be lab-rw|lab-ro|gha-rw|gha-ro" >&2; exit 2 ;;
esac

case "$ROLE" in
  writer) CERT="$TLS_DIR/client-writer.crt"; KEY="$TLS_DIR/client-writer.key"; COMBINED="$TLS_DIR/client-writer.pem" ;;
  reader) CERT="$TLS_DIR/client-reader.crt"; KEY="$TLS_DIR/client-reader.key"; COMBINED="$TLS_DIR/client-reader.pem" ;;
  *) echo "role must be writer|reader" >&2; exit 2 ;;
esac
CA="$TLS_DIR/ca.crt"

for f in "$CA" "$CERT" "$KEY"; do
  [[ -f "$f" ]] || { echo "missing TLS material: $f" >&2; exit 1; }
done

# Combined PEM required by Buck2 OSS RE client (cert then key).
umask 077
cat "$CERT" "$KEY" >"$COMBINED"
chmod 600 "$COMBINED"

umask 077
cat >"$OUT" <<EOF
# GENERATED by scripts/cas/materialize-buckconfig-local.sh — do not commit.
# role=${ROLE} profile=${PROFILE}

[buck2]
  default_allow_cache_upload = ${UPLOAD}

[buck2_re_client]
  engine_address = ${ENDPOINT}
  cas_address = ${ENDPOINT}
  action_cache_address = ${ENDPOINT}
  instance_name = main
  tls = true
  tls_ca_certs = ${CA}
  tls_client_cert = ${COMBINED}

[cas_cache]
  remote_cache_enabled = true
  allow_cache_uploads = ${UPLOAD}

[build]
  execution_platforms = //infra/ci/buck2/cache:cache-platform
EOF
chmod 600 "$OUT"
echo "wrote ${OUT} (role=${ROLE}; profile=${PROFILE}; combined_pem=${COMBINED}; mode $(stat -f '%Lp' "$OUT" 2>/dev/null || stat -c '%a' "$OUT"))"
